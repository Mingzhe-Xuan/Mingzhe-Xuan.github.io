import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFile, access } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sandbox = vm.createContext({ window: {} });
vm.runInContext(await readFile(resolve(root, 'content.js'), 'utf8'), sandbox);
const data = sandbox.window.SITE_CONTENT;
assert.equal(data.profile.name, 'Xuan Mingzhe');
assert.equal(data.research.length, 2);
assert.deepEqual(Array.from(data.research, item => item.status), ['Working paper', 'Under review']);
assert.equal(data.acknowledgements.length, 3);
assert.equal(data.experience.length, 3);
const html = await readFile(resolve(root, 'index.html'), 'utf8');
assert.ok(html.indexOf('id="news"') < html.indexOf('id="research"'));
assert.ok(!/honors|awards|Mingzhe Xuan/i.test(html));
const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]));
data.research.forEach(item => ids.add(`research-${item.id}`));
data.experience.forEach(item => ids.add(`experience-${item.id}`));
for (const item of data.news) assert.ok(ids.has(item.href.slice(1)), `Broken news link: ${item.href}`);
const assets = [data.profile.image, data.profile.cv, 'styles.css', 'app.js', 'assets/favicon.svg', ...data.research.map(item => item.image), ...data.research.map(item => item.imageOriginal).filter(Boolean)];
for (const asset of assets) await access(resolve(root, asset));
new vm.Script(await readFile(resolve(root, 'app.js'), 'utf8'));
console.log('V2 content, facts, assets, links, and JavaScript syntax checks passed.');
